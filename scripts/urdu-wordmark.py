#!/usr/bin/env python3
"""Shapes the Urdu wordmark (بیٹھک) with HarfBuzz and writes it as SVG outlines,
so the app can show proper Nastaliq lettering without shipping a 700 KB font.

    pip install fonttools uharfbuzz
    curl -L -o NotoNastaliqUrdu.ttf "https://raw.githubusercontent.com/google/fonts/main/ofl/notonastaliqurdu/NotoNastaliqUrdu%5Bwght%5D.ttf"
    python3 scripts/urdu-wordmark.py NotoNastaliqUrdu.ttf > web/src/ui/urdu-wordmark.js

Noto Nastaliq Urdu is licensed under the SIL Open Font License 1.1.
"""
import sys
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

TEXT = "بیٹھک"
font_path = sys.argv[1]
face = hb.Face(hb.Blob.from_file_path(font_path))
font = hb.Font(face)
buf = hb.Buffer()
buf.add_str(TEXT)
buf.guess_segment_properties()
buf.language = "ur"
hb.shape(font, buf, {})

tt = TTFont(font_path)
glyphs = tt.getGlyphSet()
order = tt.getGlyphOrder()
paths, x = [], 0
minx = miny = 1e9
maxx = maxy = -1e9
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    name = order[info.codepoint]
    matrix = (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)
    pen = SVGPathPen(glyphs)
    glyphs[name].draw(TransformPen(pen, matrix))
    if pen.getCommands():
        paths.append(pen.getCommands())
    bp = BoundsPen(glyphs)
    glyphs[name].draw(TransformPen(bp, matrix))
    if bp.bounds:
        a, b, c, d = bp.bounds
        minx, miny, maxx, maxy = min(minx, a), min(miny, b), max(maxx, c), max(maxy, d)
    x += pos.x_advance

pad = 20
svg = (
    f'<svg viewBox="{minx - pad:.0f} {miny - pad:.0f} {maxx - minx + 2 * pad:.0f} {maxy - miny + 2 * pad:.0f}" '
    f'height="30" fill="currentColor" aria-hidden="true"><path d="{" ".join(paths)}"/></svg>'
)
print('// "Baithak" in Urdu (Nastaliq), as outlines from Noto Nastaliq Urdu (SIL OFL 1.1).')
print("// Generated by scripts/urdu-wordmark.py so no Urdu font has to ship with the app.")
print("export const URDU_WORDMARK = `" + svg + "`;")
